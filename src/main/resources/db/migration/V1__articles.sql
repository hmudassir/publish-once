create table articles (
	id bigint generated by default as identity primary key,
	title varchar(200) not null,
	status varchar(20) not null,
	first_published_at timestamp
);

create table subscribers (
	id bigint generated by default as identity primary key,
	email varchar(254) not null,
	constraint subscribers_email_uk unique (email)
);

create table notices (
	id bigint generated by default as identity primary key,
	article_id bigint not null,
	subscriber_id bigint not null,
	constraint notices_article_fk foreign key (article_id) references articles (id),
	constraint notices_subscriber_fk foreign key (subscriber_id) references subscribers (id),
	constraint notices_once_uk unique (article_id, subscriber_id)
);

